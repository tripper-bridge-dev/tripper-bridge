    private static final String[][] SAMPLES = {STRAIGHT, RIGHT, LEFT, MERGE, UTURN, PIN, SLIGHT, KEEPR};

    // Last entry is the mirrored U-turn (derived, not seen).
    private static final String[] NAMES = {
        "straight", "turn right", "turn left", "merge", "U-turn clockwise", "destination",
        "U-turn counter-clockwise (mirrored)", "slight left", "slight right (mirrored)", "keep right", "keep left (mirrored)"
    };
    private static final int[] ICONS = {0x09, 0x15, 0x14, 0x1B, 0x1A, 0x00, 0x3D, 0x18, 0x19, 0x27, 0x28};
    private static final boolean[][][] GRIDS = {
        grid(STRAIGHT), grid(RIGHT), grid(LEFT), grid(MERGE), grid(UTURN), grid(PIN), mirror(grid(UTURN)),
        grid(SLIGHT), mirror(grid(SLIGHT)), grid(KEEPR), mirror(grid(KEEPR))
    };

    /** Best matching known arrow, or null if the picture is not (almost exactly) one of them. */
    public static Result match(String art) {
        boolean[][] g = parse(art);
        if (g == null || count(g) < MIN_PIXELS) return null;
        Result best = null;
        for (int i = 0; i < GRIDS.length; i++) {
            double v = iou(g, GRIDS[i]);
            if (v >= MIN_IOU && (best == null || v > best.iou)) {
                best = new Result(NAMES[i], ICONS[i], v);
            }
        }
        return best;
    }

    /** Pod icon code, or -1 when unknown. */
    public static int classify(String art) {
        Result r = match(art);
        return r == null ? -1 : r.icon;
    }

    /** A stored arrow as text, for tests. 0 straight, 1 right, 2 left, 3 merge, 4 U-turn, 5 destination, 6 slight left, 7 keep right. */
    public static String templateArt(int index) {
        StringBuilder sb = new StringBuilder();
        for (String r : SAMPLES[index]) {
            sb.append(r).append('\n');
        }
        return sb.toString();
    }

    public static int templateCount() {
        return SAMPLES.length;
    }

    /** Best overlap (0..1) between two arrow pictures, allowing a small shift. For tests. */
    public static double similarity(String a, String b) {
        boolean[][] ga = parse(a);
        boolean[][] gb = parse(b);
        if (ga == null || gb == null) return 0;
        return iou(ga, gb);
    }

    private static boolean[][] grid(String[] rows) {
        boolean[][] g = new boolean[N][N];
        for (int y = 0; y < N; y++) {
            for (int x = 0; x < N; x++) {
                g[y][x] = rows[y].charAt(x) == '#';
            }
        }
        return g;
    }

    private static boolean[][] mirror(boolean[][] g) {
        boolean[][] m = new boolean[N][N];
        for (int y = 0; y < N; y++) {
            for (int x = 0; x < N; x++) {
                m[y][N - 1 - x] = g[y][x];
            }
        }
        return m;
    }

    private static boolean[][] parse(String art) {
        if (art == null) return null;
        String[] lines = art.split("\n");
        if (lines.length < N) return null;
        boolean[][] g = new boolean[N][N];
        for (int y = 0; y < N; y++) {
            String l = lines[y].trim();
            if (l.length() != N) return null;
            for (int x = 0; x < N; x++) {
                char c = l.charAt(x);
                if (c == '#') {
                    g[y][x] = true;
                } else if (c != '.') {
                    return null;
                }
            }
        }
        return g;
    }

    private static int count(boolean[][] g) {
        int n = 0;
        for (int y = 0; y < N; y++) {
            for (int x = 0; x < N; x++) {
                if (g[y][x]) n++;
            }
        }
        return n;
    }

    private static double iou(boolean[][] a, boolean[][] b) {
        int ca = count(a);
        int cb = count(b);
        double best = 0;
        for (int dy = -MAX_SHIFT; dy <= MAX_SHIFT; dy++) {
            for (int dx = -MAX_SHIFT; dx <= MAX_SHIFT; dx++) {
                int inter = 0;
                for (int y = 0; y < N; y++) {
                    int ty = y + dy;
                    if (ty < 0 || ty >= N) continue;
                    for (int x = 0; x < N; x++) {
                        int tx = x + dx;
                        if (tx < 0 || tx >= N) continue;
                        if (a[y][x] && b[ty][tx]) inter++;
                    }
                }
                int uni = ca + cb - inter;
                if (uni > 0) {
                    best = Math.max(best, (double) inter / uni);
                }
            }
        }
        return best;
    }
